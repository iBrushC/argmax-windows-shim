"""
Regenerate MAPPING.md from the @mirrors decorators.

    python -m argmax_shim.reference              # writes ./MAPPING.md
    python -m argmax_shim.reference out.md       # custom path
    python -m argmax_shim.reference -            # print to stdout

Importing this module does not load any model or optional dependency.
"""

from __future__ import annotations

import importlib
import sys
from collections import defaultdict
from pathlib import Path

from ._reference import REGISTRY, Fidelity

MODULES = [
    "argmax_shim.core.audio",
    "argmax_shim.core.model_store",
    "argmax_shim.whisperkit.config",
    "argmax_shim.whisperkit.datatypes",
    "argmax_shim.whisperkit.utils",
    "argmax_shim.whisperkit.whisperkit",
    "argmax_shim.speakerkit.datatypes",
    "argmax_shim.speakerkit.config",
    "argmax_shim.speakerkit.speakerkit",
    "argmax_shim.ttskit.datatypes",
    "argmax_shim.ttskit.config",
    "argmax_shim.ttskit.ttskit",
    "argmax_shim.ttskit.audio_output",
    "argmax_shim.argmax.sdk",
    "argmax_shim.argmax.custom_vocabulary",
    "argmax_shim.argmax.whisperkit_pro",
    "argmax_shim.argmax.streaming",
    "argmax_shim.argmax.live_transcriber",
    "argmax_shim.argmax.speakerkit_pro",
]

KIT_TITLES = {
    "core": "Core (shared audio + model management)",
    "whisperkit": "WhisperKit (open-source speech-to-text)",
    "speakerkit": "SpeakerKit (open-source diarization)",
    "ttskit": "TTSKit (open-source text-to-speech)",
    "argmax": "Argmax Pro SDK (`import Argmax`)",
}


def load_all() -> None:
    for name in MODULES:
        importlib.import_module(name)


def mapping_markdown() -> str:
    load_all()
    groups: dict[str, list[tuple[str, object]]] = defaultdict(list)
    for qualname, ref in sorted(REGISTRY.items()):
        kit = qualname.split(".")[1]
        groups[kit].append((qualname, ref))

    counts = defaultdict(int)
    for ref in REGISTRY.values():
        counts[ref.fidelity] += 1

    out = [
        "# Shim to Argmax SDK mapping",
        "",
        "Generated by `python -m argmax_shim.reference`. Do not edit by hand.",
        "",
        "Each row maps a Python declaration in this shim to the Swift declaration in the Argmax SDK.",
        "Fidelity levels: **exact** (same semantics), **approximate** (same shape, different internals),",
        "**no-op** (accepted for compatibility, does nothing), **shim-only** (delete when swapping).",
        "",
        "Totals: " + ", ".join(f"{f.value}: {counts[f]}" for f in Fidelity),
        "",
    ]
    for kit in ["core", "whisperkit", "speakerkit", "ttskit", "argmax"]:
        if kit not in groups:
            continue
        out += [f"## {KIT_TITLES[kit]}", "", "| Python (shim) | Argmax module | Argmax declaration | Fidelity | Notes |", "|---|---|---|---|---|"]
        for qualname, ref in groups[kit]:
            short = qualname.replace("argmax_shim.", "")
            notes = ref.notes.replace("|", "\\|")
            swift = ref.swift.replace("|", "\\|")
            out.append(f"| `{short}` | {ref.module} | `{swift}` | {ref.fidelity.value} | {notes} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    text = mapping_markdown()
    target = argv[0] if argv else "MAPPING.md"
    if target == "-":
        print(text)
    else:
        Path(target).write_text(text, encoding="utf-8")
        print(f"Wrote {target} ({len(REGISTRY)} declarations)")


if __name__ == "__main__":
    main()
